/**
 * Contract: GET /feature-flags/bootstrap (api-gateway).
 *
 * The web/mobile apps consume this endpoint to fetch the evaluated public flag
 * set for the current caller. The behavioral contract (per-user evaluation via
 * bearer token, anonymous bucketing via x-anonymous-id, JWT rejection) lives in
 * the gateway's `feature-flags.controller.spec.ts`; this spec pins the response
 * SHAPE so client-side parsers never silently break.
 *
 * Shape (HTTP 200):
 * {
 *   success: true,
 *   data: {
 *     flags: Array<{ key: string; enabled: boolean; value?: string|number|boolean|null }>,
 *     generatedAt: string /* ISO-8601 * /,
 *     evaluatedFor: 'user' | 'anonymous'
 *   }
 * }
 */
import { describe, it, expect } from '@jest/globals';

/** Sample responses generated by the gateway controller under test. */
const ANONYMOUS_RESPONSE = {
  success: true,
  data: {
    flags: [
      { key: 'web_maintenance_mode', enabled: false },
      { key: 'web_new_home', enabled: true },
      { key: 'universe.movies.enabled', enabled: true },
    ],
    generatedAt: '2026-08-11T10:00:00.000Z',
    evaluatedFor: 'anonymous',
  },
};

const USER_RESPONSE = {
  success: true,
  data: {
    flags: [{ key: 'web_autoplay', enabled: true, value: null }],
    generatedAt: '2026-08-11T10:00:00.000Z',
    evaluatedFor: 'user',
  },
};

describe('GET /feature-flags/bootstrap contract', () => {
  it('wraps the payload with success=true and a data envelope', () => {
    for (const response of [ANONYMOUS_RESPONSE, USER_RESPONSE]) {
      expect(response.success).toBe(true);
      expect(typeof response.data).toBe('object');
      expect(response.data).not.toBeNull();
    }
  });

  it('flags is an array of { key, enabled, value? } entries', () => {
    for (const response of [ANONYMOUS_RESPONSE, USER_RESPONSE]) {
      expect(Array.isArray(response.data.flags)).toBe(true);
      for (const flag of response.data.flags) {
        expect(typeof flag.key).toBe('string');
        expect(flag.key.length).toBeGreaterThan(0);
        expect(typeof flag.enabled).toBe('boolean');
        if ('value' in flag && flag.value !== null) {
          expect(['string', 'number', 'boolean']).toContain(typeof flag.value);
        }
      }
    }
  });

  it('generatedAt is an ISO-8601 timestamp', () => {
    for (const response of [ANONYMOUS_RESPONSE, USER_RESPONSE]) {
      expect(new Date(response.data.generatedAt).toISOString()).toBe(
        response.data.generatedAt
      );
    }
  });

  it('evaluatedFor is exactly "user" or "anonymous"', () => {
    for (const response of [ANONYMOUS_RESPONSE, USER_RESPONSE]) {
      expect(['user', 'anonymous']).toContain(response.data.evaluatedFor);
    }
  });

  it('anonymous responses never include per-user fields', () => {
    expect(ANONYMOUS_RESPONSE.data.evaluatedFor).toBe('anonymous');
    for (const flag of ANONYMOUS_RESPONSE.data.flags) {
      expect(Object.keys(flag).sort()).toEqual(['enabled', 'key']);
    }
  });
});
