#!/usr/bin/env node
// ============================================================================
// generate-domain-env.mjs — derive deploy/domains.env from the shared domain
// registry (packages/shared-types/src/platform-domains.json).
//
// CI workflows and compose files consume these values instead of hardcoding
// hostnames, so the registry is the only place a domain is changed.
//
// Usage:
//   node scripts/generate-domain-env.mjs          # write deploy/domains.env
//   node scripts/generate-domain-env.mjs --check  # fail if the file is stale
// Exit codes: 0 = written / up to date, 1 = stale (--check) or invalid registry.
// ============================================================================

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const REGISTRY_RELATIVE_PATH = 'packages/shared-types/src/platform-domains.json';
export const OUTPUT_RELATIVE_PATH = 'deploy/domains.env';

// Env var name for each registry subdomain key.
export const ENV_NAMES = {
  app: 'APP_HOST',
  api: 'API_HOST',
  admin: 'ADMIN_HOST',
  creator: 'CREATOR_HOST',
  cdn: 'CDN_HOST',
  media: 'MEDIA_HOST',
  stream: 'STREAM_HOST',
  runbooks: 'RUNBOOKS_HOST',
  stagingRoot: 'STAGING_HOST',
  stagingApi: 'STAGING_API_HOST',
};

const LABEL_RE = /^[a-z0-9-]+$/;

/** Builds the env file text from a parsed registry. Throws on invalid input. */
export function renderDomainEnv(registry) {
  const base = registry?.baseDomain;
  if (typeof base !== 'string' || !/^[a-z0-9-]+(\.[a-z0-9-]+)+$/.test(base)) {
    throw new Error(`invalid baseDomain in ${REGISTRY_RELATIVE_PATH}: ${base}`);
  }
  const subs = registry.subdomains ?? {};
  const lines = [
    '# GENERATED by scripts/generate-domain-env.mjs — do not edit by hand.',
    '# Source: packages/shared-types/src/platform-domains.json',
    `BASE_DOMAIN=${base}`,
  ];
  for (const [key, envName] of Object.entries(ENV_NAMES)) {
    if (!(key in subs)) throw new Error(`registry is missing subdomain "${key}"`);
    const label = subs[key];
    if (label !== '' && !LABEL_RE.test(label)) {
      throw new Error(`invalid label for "${key}": ${label}`);
    }
    lines.push(`${envName}=${label ? `${label}.${base}` : base}`);
  }
  return lines.join('\n') + '\n';
}

function main() {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const checkOnly = process.argv.includes('--check');
  const target = path.join(root, OUTPUT_RELATIVE_PATH);
  try {
    const registry = JSON.parse(fs.readFileSync(path.join(root, REGISTRY_RELATIVE_PATH), 'utf8'));
    const next = renderDomainEnv(registry);
    if (checkOnly) {
      const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
      if (current !== next) {
        console.error(
          `✗ ${OUTPUT_RELATIVE_PATH} is stale. Run: node scripts/generate-domain-env.mjs`
        );
        process.exit(1);
      }
      console.log(`${OUTPUT_RELATIVE_PATH} is up to date.`);
      return;
    }
    fs.writeFileSync(target, next);
    console.log(`Wrote ${OUTPUT_RELATIVE_PATH}`);
  } catch (err) {
    console.error(`✗ generate-domain-env: ${err.message}`);
    process.exit(1);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
