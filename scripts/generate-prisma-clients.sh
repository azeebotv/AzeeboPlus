#!/usr/bin/env bash
# ============================================================
# Azeebo+ — Generate Prisma Clients (every schema)
# ============================================================
# Runs `prisma generate` for every canonical schema.prisma in
# the monorepo so tests, typecheck, and builds work right after
# a fresh `pnpm install --frozen-lockfile` (generated clients
# are gitignored and are NOT restored by install — which is
# exactly what used to break the payment/wallet e2e suites:
# "Cannot find module '.prisma/client/default'").
#
# Layout notes (matches Dockerfile.all-in-one):
#   - Every service/app schema declares a custom `output`
#     (src/prisma/client, or src/generated/prisma for the
#     admin/creator apps) and only writes there.
#   - packages/shared-services is the ONE schema WITHOUT a
#     custom output — its generate populates the shared
#     node_modules/.prisma/client that `@prisma/client` imports
#     resolve to. Services whose suites import `@prisma/client`
#     at module load (payment/wallet e2e + integration) depend
#     on that shared client existing.
#   - Generated schema copies under dist/, src/generated/,
#     prisma/client/, and src/prisma/client/ are excluded so we
#     only generate from the source-of-truth schemas.
#
# prisma generate validates the datasource URL even though it
# never connects, so a dummy DATABASE_URL is used unless one is
# already exported.
#
# Usage:
#   ./scripts/generate-prisma-clients.sh
#   DATABASE_URL=postgresql://user:pass@host:5432/db ./scripts/generate-prisma-clients.sh
#
# Hooks (all CI jobs call `pnpm run prisma:generate` before
# their test/typecheck/build steps; the root `test` script runs
# it too, so a local `pnpm test` sweep is self-sufficient).
# ============================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT_DIR="$(dirname "$SCRIPT_DIR")"

# ---- Colors ----
if [ -t 1 ]; then
  RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[0;33m'
  CYAN='\033[0;36m'; BOLD='\033[1m'; RESET='\033[0m'
else
  RED=''; GREEN=''; YELLOW=''; CYAN=''; BOLD=''; RESET=''
fi

log()    { printf "%s${CYAN}[INFO]${RESET}  %s\n" "$(date '+%H:%M:%S')" "$*"; }
ok()     { printf "%s${GREEN}[  OK]${RESET}  %s\n" "$(date '+%H:%M:%S')" "$*"; }
warn()   { printf "%s${YELLOW}[WARN]${RESET}  %s\n" "$(date '+%H:%M:%S')" "$*"; }
error()  { printf "%s${RED}[FAIL]${RESET}  %s\n" "$(date '+%H:%M:%S')" "$*" >&2; }
section(){ echo ""; printf "%s${BOLD}── %s ──%s\n" "$CYAN" "$1" "$RESET"; }

# prisma generate validates the datasource URL even though it
# makes no connection; allow an override, fall back to a dummy.
DATABASE_URL="${DATABASE_URL:-postgresql://azeebo:azeebo@localhost:5432/azeebo?schema=public}"
export DATABASE_URL

section "Discovering Prisma schemas"
# bash 3.2 (macOS default) has no mapfile, so populate via a read loop.
SCHEMAS=()
while IFS= read -r schema; do
  SCHEMAS+=("$schema")
done < <(find "$ROOT_DIR/services" "$ROOT_DIR/apps" "$ROOT_DIR/packages" \
  -maxdepth 5 -name schema.prisma \
  -not -path "*/node_modules/*" \
  -not -path "*/dist/*" \
  -not -path "*/prisma/client/*" \
  -not -path "*/src/prisma/*" \
  -not -path "*/generated/*" \
  | sort)
log "Found ${#SCHEMAS[@]} schema(s) to generate"

failed=0
i=0
for schema in "${SCHEMAS[@]}"; do
  i=$((i + 1))
  proj_dir="$(dirname "$(dirname "$schema")")"  # <proj>/prisma/schema.prisma -> <proj>
  name="$(basename "$proj_dir")"
  if gen_output="$(cd "$proj_dir" && pnpm exec prisma generate --no-hints 2>&1)"; then
    ok "  [$i/${#SCHEMAS[@]}] $name"
  else
    error "  [$i/${#SCHEMAS[@]}] $name"
    printf '%s\n' "$gen_output" | sed 's/^/    /' >&2 || true
    failed=$((failed + 1))
  fi
done

section "Verifying shared @prisma/client"
# The default-location client (what `@prisma/client` imports
# resolve to) is produced only by packages/shared-services —
# the one schema without a custom output. Confirm it exists so
# payment/wallet e2e + integration suites can load.
if (cd "$ROOT_DIR" && node -e "require('@prisma/client')" >/dev/null 2>&1); then
  ok "shared @prisma/client resolves (generated by packages/shared-services)"
else
  error "shared @prisma/client does not resolve"
  warn "The default-location client is produced ONLY by packages/shared-services"
  warn "(the one schema without a custom output). If its generate reported OK"
  warn "above, investigate your pnpm layout before running the test sweep."
  failed=$((failed + 1))
fi

echo ""
if [ "$failed" -gt 0 ]; then
  error "$failed schema(s) failed to generate"
  exit 1
fi
log "Prisma clients generated for all ${#SCHEMAS[@]} schema(s)"
