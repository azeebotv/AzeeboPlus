#!/usr/bin/env node
// ============================================================================
// check-licenses.mjs — CI license gate for the production dependency tree
//
// Runs `pnpm licenses list --prod --json`, fails on any package whose license
// is not permissive and not explicitly allowlisted, and (with
// --write-attribution) regenerates THIRD_PARTY_NOTICES.md.
//
// Allowlist policy: the root LICENSE is proprietary, so the prod tree must
// only contain permissively-licensed packages we can redistribute attribution
// for. Copyleft-only (GPL) and Unknown licenses need a human decision —
// each entry below carries the reason it was accepted.
//
// Usage:
//   node scripts/check-licenses.mjs                    # enforce (CI)
//   node scripts/check-licenses.mjs --write-attribution
// ============================================================================

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

// Permissive licenses acceptable in the prod tree (redistributable with
// attribution; SPDX expressions are matched substring-wise, so dual licenses
// like "BSD-3-Clause OR GPL-2.0" pass via their permissive branch).
const PERMISSIVE = [
  'MIT',
  'ISC',
  'APACHE',
  'BSD',
  '0BSD',
  'CC0',
  'CC-BY',
  'BLUE-OAK',
  'UNLICENSED', // never published / private — not a license risk
  'PYTHON-2.0',
  'POSTGRES',
  'WTFPL',
  'ZLIB',
  'MPL',
];

// Explicitly accepted exceptions: package name → reason. Anything not listed
// here and not permissive fails the gate.
const ALLOWLIST = {
  'big-integer': 'Unlicense (public domain) — transitive of decimal.js/light in wallet math',
  'stream-buffers': 'Unlicense (public domain) — transitive of request/stream tooling',
  pause: 'Unknown license, 2-line stream helper — transitive of body-parser',
  // BlueOak-1.0.0 (https://blueoakcouncil.org/license/1.0.0) is a modern
  // permissive license functionally equivalent to MIT — the ISA WG retired it
  // in favor of MIT re-licensing, but the published versions are stuck on it.
  glob: 'BlueOak-1.0.0 (MIT-equivalent, permissive)',
  jackspeak: 'BlueOak-1.0.0 (MIT-equivalent, permissive)',
  'lru-cache': 'BlueOak-1.0.0 (MIT-equivalent, permissive)',
  minimatch: 'BlueOak-1.0.0 (MIT-equivalent, permissive)',
  minipass: 'BlueOak-1.0.0 (MIT-equivalent, permissive)',
  'package-json-from-dist': 'BlueOak-1.0.0 (MIT-equivalent, permissive)',
  'path-scurry': 'BlueOak-1.0.0 (MIT-equivalent, permissive)',
  sax: 'BlueOak-1.0.0 (MIT-equivalent, permissive)',
  // sharp's prebuilt libvips binaries (LGPL-3.0-or-later). SaaS use of an
  // LGPL library is permitted without source obligations (no distribution of
  // the app to users); the binaries are dynamically linked and replaceable.
  '@img/sharp-libvips-darwin-arm64': 'LGPL-3.0-or-later libvips binary — SaaS use permitted, dynamically linked',
  '@img/sharp-libvips-linux-x64': 'LGPL-3.0-or-later libvips binary — SaaS use permitted, dynamically linked',
  '@img/sharp-libvips-linuxmusl-x64': 'LGPL-3.0-or-later libvips binary — SaaS use permitted, dynamically linked',
  // SIL Open Font License 1.1 — standard permissive font license for self-hosted
  // Inter & Montserrat fonts in apps/web (bundled instead of next/font/google).
  '@fontsource/inter': 'OFL-1.1 (SIL Open Font License — permissive, self-hosted web font)',
  '@fontsource/montserrat': 'OFL-1.1 (SIL Open Font License — permissive, self-hosted web font)',
};

const ATTRIBUTION_FILE = 'THIRD_PARTY_NOTICES.md';

function loadProdLicenses() {
  const out = execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], {
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
    shell: process.platform === 'win32',
  });
  // Shape: { "<license>": [ { name, versions, paths, license, homepage, ... } ] }
  return JSON.parse(out);
}

function isPermissive(license) {
  const L = (license || '').toUpperCase();
  return PERMISSIVE.some((p) => L.includes(p));
}

function collectViolations(data) {
  const violations = [];
  for (const [license, pkgs] of Object.entries(data)) {
    if (isPermissive(license)) continue;
    for (const pkg of pkgs) {
      if (ALLOWLIST[pkg.name]) continue;
      violations.push({ name: pkg.name, versions: pkg.versions, license });
    }
  }
  return violations;
}

function writeAttribution(data) {
  const lines = [
    '# Third-Party Notices',
    '',
    'Attribution for production dependencies of the Azeebo+ platform.',
    'Regenerated by `pnpm ops:licenses --write-attribution` — do not edit by hand.',
    '',
  ];
  for (const [license, pkgs] of Object.entries(data)) {
    lines.push(`## ${license}`, '');
    for (const pkg of pkgs.sort((a, b) => a.name.localeCompare(b.name))) {
      const versions = pkg.versions.join(', ');
      const home = pkg.homepage ? ` — ${pkg.homepage}` : '';
      lines.push(`- **${pkg.name}** ${versions}${home} (${pkg.license})`);
    }
    lines.push('');
  }
  writeFileSync(ATTRIBUTION_FILE, lines.join('\n'));
  console.log(`Wrote ${ATTRIBUTION_FILE}`);
}

const data = loadProdLicenses();

if (process.argv.includes('--write-attribution')) {
  writeAttribution(data);
}

const violations = collectViolations(data);
if (violations.length > 0) {
  console.error('License gate FAILED — non-permissive packages not in the allowlist:');
  for (const v of violations) {
    console.error(`  - ${v.name}@${v.versions.join(', ')} [${v.license}]`);
  }
  console.error(
    '\nAdd an entry to ALLOWLIST in scripts/check-licenses.mjs (with a reason) or replace the dependency.'
  );
  process.exit(1);
}
console.log('License gate passed: all production dependencies are permissive or allowlisted.');
