export type SupportedLanguage = keyof typeof resources;

export const LANGUAGES: { code: SupportedLanguage; name: string; nativeName: string }[] = [
  { code: 'en', name: 'English', nativeName: 'English' },
  { code: 'fr', name: 'French', nativeName: 'Français' },
  { code: 'pt', name: 'Portuguese', nativeName: 'Português' },
  { code: 'ha', name: 'Hausa', nativeName: 'Hausa' },
  { code: 'yo', name: 'Yoruba', nativeName: 'Yorùbá' },
  { code: 'ig', name: 'Igbo', nativeName: 'Igbo' },
  { code: 'pcm', name: 'Nigerian Pidgin', nativeName: 'Naija Pidgin' },
];

// Detect browser language
function detectBrowserLanguage(): SupportedLanguage {
  try {
    if (typeof window === 'undefined') return 'en';
    const lang = navigator.language?.split('-')[0]?.toLowerCase() || 'en';
    if (LANGUAGES.some((l) => l.code === lang)) {
      return lang as SupportedLanguage;
    }
  } catch {
    // fallback to English
  }
  return 'en';
}

const savedLang = typeof window !== 'undefined' ? localStorage.getItem('@azeebo/language') : null;

const detectedLang = detectBrowserLanguage();

i18n.use(initReactI18next as unknown as Parameters<typeof i18n.use>[0]).init({
  resources,
  lng: savedLang || detectedLang || 'en',
  fallbackLng: 'en',
  interpolation: {
    escapeValue: false,
  },
});

export async function changeLanguage(language: SupportedLanguage): Promise<void> {
  await i18n.changeLanguage(language);
  if (typeof window !== 'undefined') {
    localStorage.setItem('@azeebo/language', language);
  }
  // Update html lang attribute
  if (typeof document !== 'undefined') {
    document.documentElement.lang = language;
  }
}

export default i18n;
