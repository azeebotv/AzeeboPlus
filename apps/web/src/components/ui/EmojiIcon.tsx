export type EmojiIconProps = {
  emoji: string;
  size?: 'xs' | 'sm' | 'md' | 'lg' | 'xl';
  className?: string;
};

const SIZE_CLASSES = {
  xs: 'w-3 h-3',
  sm: 'w-4 h-4',
  md: 'w-5 h-5',
  lg: 'w-8 h-8',
  xl: 'w-12 h-12',
};

/**
 * Renders an emoji character as a Lucide React icon.
 * Falls back to the emoji as text if no mapping is found.
 */
export function EmojiIcon({ emoji, size = 'md', className = '' }: EmojiIconProps) {
  const IconComponent = EMOJI_MAP[emoji];

  if (IconComponent) {
    return (
      <IconComponent
        className={`${SIZE_CLASSES[size]} ${className}`}
        strokeWidth={1.5}
        aria-hidden="true"
      />
    );
  }

  // Fallback: render emoji as text
  return (
    <span
      className={`inline-flex items-center justify-center ${SIZE_CLASSES[size]} ${className}`}
      aria-hidden="true"
    >
      {emoji}
    </span>
  );
}

/**
 * Convert an emoji to a Lucide icon component, or null if no mapping exists.
 */
export function getEmojiIcon(emoji: string): LucideIcon | null {
  return EMOJI_MAP[emoji] || null;
}

export default EmojiIcon;
