    GRANT ALL PRIVILEGES ON DATABASE messaging_db TO messaging_user;
    GRANT ALL PRIVILEGES ON DATABASE referral_db TO referral_user;
    GRANT ALL PRIVILEGES ON DATABASE subscription_db TO subscription_user;
